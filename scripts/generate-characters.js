#!/usr/bin/env node
/**
 * Auto-generate CharacterConfig.ts from character folders
 *
 * Usage: node scripts/generate-characters.js
 *
 * This script scans public/assets/characters/ for subdirectories
 * and generates src/game/config/CharacterConfig.ts automatically.
 *
 * Requirements for each character folder:
 * - Folder name = character key (e.g., "dog")
 * - Contains {key}.png spritesheet (e.g., "dog.png")
 * - Spritesheet: 4x4 grid (16 frames), 500x500 pixels (125x125 per frame)
 */

const fs = require('fs');
const path = require('path');

const CHARACTERS_DIR = path.join(__dirname, '../public/assets/characters');
const OUTPUT_FILE = path.join(__dirname, '../src/game/config/CharacterConfig.ts');

// Default frame size (can be overridden per character if needed)
// 500x500 spritesheet with 4x4 grid = 125x125 per frame
const DEFAULT_FRAME_WIDTH = 125;
const DEFAULT_FRAME_HEIGHT = 125;

function capitalize(str) {
    return str.charAt(0).toUpperCase() + str.slice(1);
}

function scanCharacterFolders() {
    const characters = [];

    // Read all entries in characters directory
    const entries = fs.readdirSync(CHARACTERS_DIR, { withFileTypes: true });

    for (const entry of entries) {
        // Only process directories
        if (!entry.isDirectory()) continue;

        const folderName = entry.name;
        const spritesheetPath = path.join(CHARACTERS_DIR, folderName, `${folderName}.png`);

        // Check if spritesheet exists
        if (fs.existsSync(spritesheetPath)) {
            characters.push({
                key: folderName,
                displayName: capitalize(folderName),
                frameWidth: DEFAULT_FRAME_WIDTH,
                frameHeight: DEFAULT_FRAME_HEIGHT
            });
            console.log(`✓ Found character: ${folderName}`);
        } else {
            console.log(`⚠ Skipped ${folderName}: missing ${folderName}.png`);
        }
    }

    // Sort alphabetically
    characters.sort((a, b) => a.key.localeCompare(b.key));

    return characters;
}

function generateConfigFile(characters) {
    const charactersJson = characters.map(c =>
        `    { key: '${c.key}', displayName: '${c.displayName}', frameWidth: ${c.frameWidth}, frameHeight: ${c.frameHeight} }`
    ).join(',\n');

    const content = `/**
 * Character Configuration (AUTO-GENERATED)
 *
 * DO NOT EDIT THIS FILE MANUALLY!
 * Run: npm run generate:characters
 *
 * To add a new character:
 * 1. Create folder: public/assets/characters/{key}/
 * 2. Add spritesheet: public/assets/characters/{key}/{key}.png
 *    - 4x4 grid (16 frames), 500x500 pixels (125x125 per frame)
 *    - Row 0: Down, Row 1: Up, Row 2: Left, Row 3: Right
 * 3. Run: npm run generate:characters
 */

export interface CharacterDefinition {
    key: string;           // Unique key for the character (also folder/file name)
    displayName: string;   // Display name shown to user
    frameWidth: number;    // Width of each frame
    frameHeight: number;   // Height of each frame
}

/**
 * List of all available playable characters
 * Generated from: public/assets/characters/
 */
export const PLAYABLE_CHARACTERS: CharacterDefinition[] = [
${charactersJson}
];

/**
 * Get character keys as readonly array
 */
export const CHARACTER_KEYS = PLAYABLE_CHARACTERS.map(c => c.key) as readonly string[];

/**
 * Default character key (first in list)
 */
export const DEFAULT_CHARACTER = PLAYABLE_CHARACTERS[0]?.key || 'lion';

/**
 * Get character definition by key
 */
export function getCharacterByKey(key: string): CharacterDefinition | undefined {
    return PLAYABLE_CHARACTERS.find(c => c.key === key);
}

/**
 * Get next character key (for cycling through characters)
 */
export function getNextCharacterKey(currentKey: string): string {
    const currentIndex = CHARACTER_KEYS.indexOf(currentKey);
    const nextIndex = (currentIndex + 1) % CHARACTER_KEYS.length;
    return CHARACTER_KEYS[nextIndex];
}
`;

    fs.writeFileSync(OUTPUT_FILE, content);
    console.log(`\n✅ Generated ${OUTPUT_FILE}`);
    console.log(`   Total characters: ${characters.length}`);
}

// Main
console.log('🔍 Scanning character folders...\n');
const characters = scanCharacterFolders();

if (characters.length === 0) {
    console.error('\n❌ No characters found!');
    process.exit(1);
}

generateConfigFile(characters);
console.log('\n🎮 Characters ready to use!');
